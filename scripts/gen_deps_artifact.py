#!/usr/bin/env python3
"""Emit the engineering-library landscape artifact from both trees' manifests.

Build-time generation (card 20261111_110106): manifests are read in the same
process as the build, so no HTTP endpoint is earned — boundary test: same
process -> function call. The artifact answers the question the /developer
surface used to answer by hand-grepping: which libraries does sloughGPT depend
on across BOTH trees, at what versions, and where do declarations disagree
(duplicates across manifests, drift between specs, names present in both trees)?

Sources (read-only — package-lock.json, conda env files and the manifests
themselves are never written):

* python — root ``pyproject.toml`` (``[project].dependencies`` +
  ``[project.optional-dependencies]``), root ``requirements.txt``, and
  ``packages|apps/*/pyproject.toml``. Root ``setup.py`` declares no
  ``install_requires``, so there is nothing to read.
* js — root ``package.json`` plus every ``package.json`` under ``apps/`` and
  ``packages/`` (npm workspace members and ``apps/mobile``, which carries its
  own toolchain but is still part of the tree the question asks about).

v1 scope is inventory + versions + duplicate/drift highlights — NOT a
vulnerability feed (no network at build).

Usage:
    python scripts/gen_deps_artifact.py           # write the artifact
    python scripts/gen_deps_artifact.py --check   # freshness gate (exit 1 if stale)

Freshness is gated by ``tests/test_deps_artifact.py``; every output must also
be listed in ``.prettierignore`` (lint-staged reformatting the generator's
bytes would flap the gate — same reason as ``gen_ts_contracts.OUTPUTS``).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]

# One artifact per frontend consumer (v1: the web app's /developer tab).
OUTPUTS: tuple[Path, ...] = (ROOT / "apps" / "web" / "lib" / "deps.gen.ts",)

# js manifest section -> entry kind (python kinds: runtime/optional).
JS_SECTIONS: tuple[tuple[str, str], ...] = (
    ("dependencies", "runtime"),
    ("devDependencies", "dev"),
    ("peerDependencies", "peer"),
    ("optionalDependencies", "optional"),
)

HEADER = """\
// GENERATED by scripts/gen_deps_artifact.py — do not edit by hand.
// Regenerate after changing any manifest (pyproject/requirements/package.json):
//   python scripts/gen_deps_artifact.py
// Freshness gate: tests/test_deps_artifact.py::test_artifact_is_fresh_on_this_tree
"""

TS_TYPES = """
/** One declared dependency, exactly as a manifest states it. */
export interface DepEntry {
  /** Package name as declared in the manifest. */
  name: string
  /** Normalized grouping key (PEP 503-style: lowercase, runs of [-_.] -> -). */
  key: string
  /** Declared version spec; '' when the manifest does not pin one. */
  version: string
  tree: 'python' | 'js'
  kind: 'runtime' | 'optional' | 'dev' | 'peer'
  /** Repo-relative path of the manifest that declares it. */
  manifest: string
}

/** A package grouped for duplicate/drift reporting. */
export interface DepGroup {
  key: string
  entries: DepEntry[]
  /** Distinct declared specs, sorted — more than one means drift. */
  versions: string[]
}

export interface DepsArtifact {
  /** Repo-relative manifests read, sorted. */
  manifests: string[]
  entries: DepEntry[]
  /** Same package declared by two or more manifests. */
  duplicates: DepGroup[]
  /** Same package declared with more than one distinct spec. */
  drift: DepGroup[]
  /** Normalized keys present in BOTH the python and js trees. */
  cross_tree: string[]
}
"""

_NAME_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)")
_EXTRAS_RE = re.compile(r"^\[[^\]]*\]")
_SEP_RE = re.compile(r"[-_.]+")


def parse_python_spec(spec: str) -> tuple[str, str]:
    """Split ``'uvicorn[standard]>=0.24.0 ; marker'`` -> ``('uvicorn', '>=0.24.0')``.

    Environment markers are dropped (they pin *where*, not *what*), extras are
    not part of the name, and an unpinned requirement keeps an empty spec —
    never ``None``, so the artifact's ``version`` field stays a plain string.
    """
    spec = spec.split(";", 1)[0].strip()
    match = _NAME_RE.match(spec)
    if not match:
        return spec, ""
    name = match.group(1)
    rest = _EXTRAS_RE.sub("", spec[match.end() :]).strip()
    return name, rest


def normalize(name: str) -> str:
    """Grouping key: PEP 503 normalization, applied to both trees alike.

    Cross-tree comparison needs one spelling of a name; using it for the js
    tree too means ``React`` and ``react`` group, which is what a human
    reading "where do we disagree" means by "the same package".
    """
    return _SEP_RE.sub("-", name).lower()


def _rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def _entry(
    name: str, version: str, tree: str, kind: str, manifest: str
) -> dict[str, str]:
    return {
        "name": name,
        "key": normalize(name),
        "version": version,
        "tree": tree,
        "kind": kind,
        "manifest": manifest,
    }


def _read_pyproject(path: Path, root: Path, entries: list[dict[str, str]]) -> str:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    project = data.get("project", {})
    manifest = _rel(path, root)
    for spec in project.get("dependencies", []) or []:
        name, version = parse_python_spec(str(spec))
        entries.append(_entry(name, version, "python", "runtime", manifest))
    for group in (project.get("optional-dependencies") or {}).values():
        for spec in group or []:
            name, version = parse_python_spec(str(spec))
            entries.append(_entry(name, version, "python", "optional", manifest))
    return manifest


def _read_requirements(path: Path, root: Path, entries: list[dict[str, str]]) -> str:
    manifest = _rel(path, root)
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-")):
            continue  # comment, blank, or an include/option line (-r/-e)
        name, version = parse_python_spec(line)
        if name:
            entries.append(_entry(name, version, "python", "runtime", manifest))
    return manifest


def _read_package_json(path: Path, root: Path, entries: list[dict[str, str]]) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    manifest = _rel(path, root)
    for section, kind in JS_SECTIONS:
        for name, version in (data.get(section) or {}).items():
            entries.append(_entry(name, str(version), "js", kind, manifest))
    return manifest


def _js_manifest_paths(root: Path) -> list[Path]:
    """Root package.json + every package.json under apps/ and packages/.

    ``node_modules`` is excluded explicitly: a nested dependency's manifest is
    not a declaration of THIS tree's engineering stack.
    """
    found = {root / "package.json"}
    for base in ("apps", "packages"):
        for path in (root / base).glob("**/package.json") if (root / base).is_dir() else ():
            if "node_modules" not in path.parts:
                found.add(path)
    return sorted(p for p in found if p.is_file())


def build_artifact(root: Path) -> dict[str, Any]:
    """Read every manifest under *root* and group the declarations."""
    entries: list[dict[str, str]] = []
    manifests: list[str] = []

    root_pyproject = root / "pyproject.toml"
    if root_pyproject.is_file():
        manifests.append(_read_pyproject(root_pyproject, root, entries))
    requirements = root / "requirements.txt"
    if requirements.is_file():
        manifests.append(_read_requirements(requirements, root, entries))
    for pyproject in sorted(root.glob("packages/*/pyproject.toml")) + sorted(
        root.glob("apps/*/pyproject.toml")
    ):
        manifests.append(_read_pyproject(pyproject, root, entries))
    for package_json in _js_manifest_paths(root):
        manifests.append(_read_package_json(package_json, root, entries))

    by_key: dict[str, list[dict[str, str]]] = {}
    for entry in entries:
        by_key.setdefault(entry["key"], []).append(entry)

    def _group(group_entries: list[dict[str, str]]) -> dict[str, Any]:
        return {
            "key": group_entries[0]["key"],
            "entries": sorted(
                group_entries, key=lambda e: (e["tree"], e["manifest"], e["kind"], e["name"])
            ),
            "versions": sorted({e["version"] for e in group_entries}),
        }

    duplicates = sorted(
        (
            _group(group)
            for group in by_key.values()
            if len({e["manifest"] for e in group}) > 1
        ),
        key=lambda g: g["key"],
    )
    drift = sorted(
        (_group(group) for group in by_key.values() if len({e["version"] for e in group}) > 1),
        key=lambda g: g["key"],
    )
    cross_tree = sorted(
        key
        for key, group in by_key.items()
        if {e["tree"] for e in group} == {"python", "js"}
    )

    return {
        "manifests": sorted(set(manifests)),
        "entries": sorted(
            entries, key=lambda e: (e["tree"], e["manifest"], e["key"], e["kind"])
        ),
        "duplicates": duplicates,
        "drift": drift,
        "cross_tree": cross_tree,
    }


def emit(artifact: dict[str, Any]) -> str:
    """Serialize deterministically: sorted keys, stable entry order, LF endings."""
    body = json.dumps(artifact, indent=2, sort_keys=True, ensure_ascii=False)
    return f"{HEADER}{TS_TYPES}\nexport const DEPS: DepsArtifact = {body}\n"


def build(root: Path) -> str:
    return emit(build_artifact(root))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if any committed output is stale"
    )
    args = parser.parse_args(argv)

    artifact = build_artifact(ROOT)
    content = emit(artifact)
    stale: list[str] = []
    for out in OUTPUTS:
        rel = _rel(out, ROOT)
        if args.check:
            current = out.read_text(encoding="utf-8") if out.is_file() else ""
            if current != content:
                stale.append(rel)
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")

    if args.check:
        if stale:
            print(
                f"[STALE] {', '.join(stale)} — run `python scripts/gen_deps_artifact.py`",
                file=sys.stderr,
            )
            return 1
        print(
            f"✓ deps artifact fresh: {len(artifact['entries'])} entries, "
            f"{len(artifact['duplicates'])} duplicates, {len(artifact['drift'])} drift, "
            f"{len(artifact['cross_tree'])} cross-tree"
        )
        return 0

    print(
        f"{len(artifact['entries'])} entries · {len(artifact['duplicates'])} duplicates · "
        f"{len(artifact['drift'])} drift · {len(artifact['cross_tree'])} cross-tree"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
