"""Curriculum staging — dynamic multi-stage training over ONE SloughGPTTrainer.

Card 20261115_081635_training-curriculum-staging-recipe-stage-gate-judge-dynamic.

A ``curriculum.json`` file declares an ordered list of training stages
(datasets + mixing ratios, replay % for anti-forgetting, EWC consolidation,
gate criteria). ``run_curriculum`` drives a single :class:`SloughGPTTrainer`
through every stage — model, optimizer and EWC consolidation history carry
across stage boundaries; only the *data* swaps (``swap_stage_data``). This is
the adapter seam over the one existing training loop, never N loops.

The stage-gate judge grades each stage's checkpoint before it advances:

- ``max_eval_loss`` — mean cross-entropy from ``lm_eval_char`` on held-out
  eval text (the checkpoint-fit criterion);
- ``min_quality`` / ``max_toxicity`` — ``quality_scorer`` metrics on a sample
  generated by the stage's model (the output-quality criterion).

Gate policy on failure is per stage (``on_gate_fail``): the default
``"continue"`` logs a warning, marks the checkpoint **provisional**, and
advances anyway — recorded, never silent; ``"abort"`` raises
:class:`StageGateError` and stops the curriculum.

Boundaries (same-process function calls — no transport crossing):

    shell ``train --curriculum <file>``
        → local_api route ``POST /training/curriculum``
        → ``run_curriculum()`` (this module)
"""

from __future__ import annotations

import json
import logging
import threading
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import TYPE_CHECKING, Any

import numpy as np

if TYPE_CHECKING:
    from domain.training._internal.train_pipeline import TrainerConfig

logger = logging.getLogger(__name__)

_ALLOWED_TOP_KEYS = {"version", "eval_text", "stages", "description"}
_ALLOWED_STAGE_KEYS = {
    "name",
    "datasets",
    "epochs",
    "replay",
    "ewc",
    "gate",
    "on_gate_fail",
    "eval_text",
}
_ALLOWED_GATE_KEYS = {"max_eval_loss", "min_quality", "max_toxicity"}
_ALLOWED_GATE_FAIL = ("continue", "abort")
_SUPPORTED_VERSION = 1


class CurriculumError(ValueError):
    """A curriculum.json that is missing, malformed, or violates the schema."""


class StageGateError(RuntimeError):
    """A stage-gate judge failed under ``on_gate_fail: "abort"``."""

    def __init__(self, stage: str, reason: str, metrics: dict[str, float] | None = None):
        super().__init__(f"stage gate failed for {stage!r}: {reason}")
        self.stage = stage
        self.reason = reason
        self.metrics = metrics or {}


@dataclass(frozen=True)
class GateCriteria:
    """Thresholds a stage's checkpoint must meet to advance cleanly."""

    max_eval_loss: float | None = None
    min_quality: float | None = None
    max_toxicity: float | None = None

    @property
    def is_empty(self) -> bool:
        return self.max_eval_loss is None and self.min_quality is None and self.max_toxicity is None


@dataclass(frozen=True)
class StageSpec:
    """One stage of the curriculum — a named, ordered slice of training."""

    name: str
    datasets: tuple[tuple[str, float], ...]
    epochs: int = 1
    replay: float = 0.0
    ewc: bool = False
    gate: GateCriteria = field(default_factory=GateCriteria)
    on_gate_fail: str = "continue"
    eval_text: str | None = None


@dataclass(frozen=True)
class Curriculum:
    """A validated, ordered stage list ready to run."""

    stages: tuple[StageSpec, ...]
    eval_text: str | None = None
    source_path: str = ""
    # JSON has no comments: `description` is how a curriculum documents
    # itself (e.g. marking gate thresholds as placeholders to calibrate).
    # Purely informational — the runner never reads it.
    description: str = ""


@dataclass(frozen=True)
class StageResult:
    """The judge's verdict and evidence for one completed stage."""

    name: str
    passed: bool
    provisional: bool
    metrics: dict[str, float]
    checkpoint: str
    gate_reason: str
    epochs: int


@dataclass(frozen=True)
class CurriculumReport:
    """Outcome of a curriculum run: per-stage verdicts + final checkpoint."""

    stages: tuple[StageResult, ...]
    final_checkpoint: str
    total_stages: int
    cancelled: bool = False

    @property
    def completed_all(self) -> bool:
        return not self.cancelled and len(self.stages) == self.total_stages


# ── Schema ──────────────────────────────────────────────────────────────


def _fail(msg: str) -> CurriculumError:
    return CurriculumError(f"curriculum: {msg}")


def _check_keys(obj: dict, allowed: set[str], where: str) -> None:
    unknown = sorted(set(obj) - allowed)
    if unknown:
        raise _fail(f"unknown key(s) {unknown} in {where} (allowed: {sorted(allowed)})")


def _positive(name: str, value: Any, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise _fail(f"{name} must be a number in {where}, got {value!r}")
    v = float(value)
    if v != v or v in (float("inf"), float("-inf")):
        raise _fail(f"{name} must be finite in {where}, got {value!r}")
    if v <= 0:
        raise _fail(f"{name} must be > 0 in {where}, got {value!r}")
    return v


def _parse_datasets(raw: Any, where: str) -> tuple[tuple[str, float], ...]:
    if not isinstance(raw, list) or not raw:
        raise _fail(f"datasets must be a non-empty list in {where}")
    pairs: list[tuple[str, float]] = []
    for i, entry in enumerate(raw):
        if not isinstance(entry, dict):
            raise _fail(f"datasets[{i}] must be an object in {where}")
        _check_keys(entry, {"path", "ratio"}, f"{where} datasets[{i}]")
        path = entry.get("path")
        if not isinstance(path, str) or not path.strip():
            raise _fail(f"datasets[{i}].path must be a non-empty string in {where}")
        ratio = _positive("ratio", entry.get("ratio"), f"{where} datasets[{i}]")
        pairs.append((path, ratio))
    total = sum(r for _, r in pairs)
    return tuple((p, r / total) for p, r in pairs)


def _parse_gate(raw: Any, where: str, eval_text: str | None) -> GateCriteria:
    if raw is None:
        return GateCriteria()
    if not isinstance(raw, dict):
        raise _fail(f"gate must be an object in {where}")
    _check_keys(raw, _ALLOWED_GATE_KEYS, f"{where} gate")
    kwargs: dict[str, float | None] = {}
    for key in _ALLOWED_GATE_KEYS:
        if key in raw and raw[key] is not None:
            kwargs[key] = _positive(key, raw[key], f"{where} gate")
    gate = GateCriteria(**kwargs)
    if gate.max_eval_loss is not None and not eval_text:
        raise _fail(f"gate.max_eval_loss requires an eval_text (stage or top-level) in {where}")
    return gate


def _parse_stage(raw: Any, index: int, eval_text: str | None) -> StageSpec:
    where = f"stages[{index}]"
    if not isinstance(raw, dict):
        raise _fail(f"{where} must be an object")
    _check_keys(raw, _ALLOWED_STAGE_KEYS, where)

    name = raw.get("name")
    if not isinstance(name, str) or not name.strip():
        raise _fail(f"{where}.name must be a non-empty string")

    epochs = raw.get("epochs", 1)
    if isinstance(epochs, bool) or not isinstance(epochs, int) or epochs < 1:
        raise _fail(f"{where}.epochs must be an integer >= 1, got {epochs!r}")

    replay = raw.get("replay", 0.0)
    if isinstance(replay, bool) or not isinstance(replay, (int, float)):
        raise _fail(f"{where}.replay must be a number in [0, 1], got {replay!r}")
    replay = float(replay)
    if not 0.0 <= replay <= 1.0:
        raise _fail(f"{where}.replay must be in [0, 1], got {replay!r}")

    ewc = raw.get("ewc", False)
    if not isinstance(ewc, bool):
        raise _fail(f"{where}.ewc must be a boolean, got {ewc!r}")

    policy = raw.get("on_gate_fail", "continue")
    if policy not in _ALLOWED_GATE_FAIL:
        raise _fail(f"{where}.on_gate_fail must be one of {_ALLOWED_GATE_FAIL}, got {policy!r}")

    stage_eval = raw.get("eval_text")
    if stage_eval is not None and (not isinstance(stage_eval, str) or not stage_eval.strip()):
        raise _fail(f"{where}.eval_text must be a non-empty string when present")

    gate = _parse_gate(raw.get("gate"), where, stage_eval or eval_text)

    return StageSpec(
        name=name.strip(),
        datasets=_parse_datasets(raw.get("datasets"), where),
        epochs=epochs,
        replay=replay,
        ewc=ewc,
        gate=gate,
        on_gate_fail=policy,
        eval_text=stage_eval,
    )


def load_curriculum(path: str | Path) -> Curriculum:
    """Load and strictly validate a ``curriculum.json``.

    Args:
        path: path to the JSON file.

    Returns:
        A validated :class:`Curriculum`.

    Raises:
        CurriculumError: file missing, invalid JSON, or any schema violation
            (unknown keys are rejected so typos never silently default).
    """
    p = Path(path)
    if not p.is_file():
        raise _fail(f"file not found: {p}")
    try:
        doc = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise _fail(f"invalid JSON in {p}: {exc}") from exc
    if not isinstance(doc, dict):
        raise _fail(f"top level must be an object in {p}")

    _check_keys(doc, _ALLOWED_TOP_KEYS, "top level")

    version = doc.get("version")
    if version != _SUPPORTED_VERSION:
        raise _fail(f"unsupported version {version!r} (expected {_SUPPORTED_VERSION})")

    eval_text = doc.get("eval_text")
    if eval_text is not None and (not isinstance(eval_text, str) or not eval_text.strip()):
        raise _fail("eval_text must be a non-empty string when present")

    description = doc.get("description")
    if description is not None and (not isinstance(description, str) or not description.strip()):
        raise _fail("description must be a non-empty string when present")

    raw_stages = doc.get("stages")
    if not isinstance(raw_stages, list) or not raw_stages:
        raise _fail("stages must be a non-empty list")

    stages = tuple(_parse_stage(s, i, eval_text) for i, s in enumerate(raw_stages))
    seen: set[str] = set()
    for s in stages:
        if s.name in seen:
            raise _fail(f"duplicate stage name {s.name!r}")
        seen.add(s.name)

    return Curriculum(
        stages=stages,
        eval_text=eval_text,
        source_path=str(p),
        description=description or "",
    )


# ── Stage mixing (ratios + replay) ──────────────────────────────────────


def compute_stage_mix(stage: StageSpec, completed_paths: Sequence[str]) -> list[tuple[str, float]]:
    """Build the ``(path, ratio)`` blend for one stage.

    The stage's own datasets keep ``1 - replay`` of the mix (rescaled to their
    relative ratios); the replay slice is split uniformly over the *unique*
    dataset paths of already-completed stages. Replay on the first stage (no
    completed paths) is a no-op.

    Args:
        stage: the stage being entered.
        completed_paths: dataset paths of stages already trained, in order.

    Returns:
        ``(path, ratio)`` pairs summing to 1.0.
    """
    own_total = sum(r for _, r in stage.datasets)
    own = [(p, r / own_total) for p, r in stage.datasets]

    unique_completed = list(dict.fromkeys(completed_paths))
    if stage.replay <= 0.0 or not unique_completed:
        return own

    keep = 1.0 - stage.replay
    replay_share = stage.replay / len(unique_completed)
    mix = [(p, r * keep) for p, r in own]
    mix.extend((p, replay_share) for p in unique_completed)
    # guard float drift so callers can rely on sum == 1.0
    total = sum(r for _, r in mix)
    return [(p, r / total) for p, r in mix]


# ── Stage-gate judge ────────────────────────────────────────────────────


def _eval_loss(checkpoint: str, eval_text: str) -> float:
    """Mean cross-entropy of ``checkpoint`` on ``eval_text`` (lm_eval_char)."""
    from domain.training._internal.lm_eval_char import evaluate_soul_char_lm

    metrics = evaluate_soul_char_lm(checkpoint, eval_text)
    return float(metrics["mean_loss"])


def _decode(ids: Any, itos: dict) -> str:
    """Decode token ids with the trainer's itos (int- or str-keyed)."""
    out = []
    for i in ids:
        try:
            ch = itos.get(int(i))
        except (TypeError, ValueError):
            ch = None
        if ch is None:
            ch = itos.get(str(int(i)), "")
        out.append(ch)
    return "".join(out)


def _sample_metrics(
    trainer: Any,
    *,
    max_new_tokens: int = 200,
    temperature: float = 0.8,
    min_chars: int = 100,
) -> dict[str, float] | None:
    """Generate a sample from the trainer's live model and score it.

    Returns ``{avg_quality, toxicity_rate, ...}`` from ``quality_scorer``,
    or ``None`` when no usable sample exists (no generator, or a sample too
    short to score) — the caller must treat that as *cannot evaluate*, never
    as a pass.
    """
    from domain.training._internal.quality_scorer import compute_data_quality

    model = getattr(trainer, "model", None)
    generate = getattr(model, "generate", None)
    if generate is None:
        return None
    itos = getattr(trainer, "itos", None)
    if not itos:
        return None
    try:
        seed = np.zeros((1, 1), dtype=np.int64)
        out = generate(seed, max_new_tokens=max_new_tokens, temperature=temperature)
        ids = np.asarray(out)[0]
        text = _decode(ids[1:] if len(ids) > 1 else ids, itos)
    except Exception as exc:  # noqa: BLE001 — a generation failure is "no sample"
        logger.debug("gate sample generation failed: %s", exc)
        return None
    if len(text) < min_chars:
        return None
    return compute_data_quality(text)


def evaluate_stage_gate(
    trainer: Any,
    stage: StageSpec,
    *,
    checkpoint: str,
    eval_text: str,
) -> tuple[bool, str, dict[str, float]]:
    """Grade one stage's checkpoint against its gate criteria.

    Args:
        trainer: the trainer holding the stage's live model (for sampling).
        stage: the stage whose gate is evaluated.
        checkpoint: path to the stage's saved checkpoint (for eval loss).
        eval_text: resolved eval-text path (stage-level or curriculum-level).

    Returns:
        ``(passed, reason, metrics)`` — ``reason`` is ``""`` on pass and a
        human-readable list of violations on failure. An empty gate passes
        vacuously; an unmeasurable criterion FAILS (never a silent pass).
    """
    gate = stage.gate
    if gate.is_empty:
        return True, "", {}

    metrics: dict[str, float] = {}
    reasons: list[str] = []

    if gate.max_eval_loss is not None:
        if not eval_text:
            reasons.append("cannot evaluate eval_loss: no eval_text configured")
        else:
            loss = _eval_loss(checkpoint, eval_text)
            metrics["eval_loss"] = loss
            if loss > gate.max_eval_loss:
                reasons.append(f"eval_loss {loss:.4f} > max_eval_loss {gate.max_eval_loss}")

    if gate.min_quality is not None or gate.max_toxicity is not None:
        sample = _sample_metrics(trainer)
        if sample is None:
            reasons.append(
                "cannot evaluate quality/toxicity: no usable model sample "
                "(generation unavailable or sample too short)"
            )
        else:
            metrics.update({k: float(v) for k, v in sample.items()})
            if gate.min_quality is not None and sample.get("avg_quality", 0.0) < gate.min_quality:
                reasons.append(
                    f"quality {sample.get('avg_quality', 0.0)} < min_quality {gate.min_quality}"
                )
            if (
                gate.max_toxicity is not None
                and sample.get("toxicity_rate", 0.0) > gate.max_toxicity
            ):
                reasons.append(
                    f"toxicity {sample.get('toxicity_rate', 0.0)} > max_toxicity {gate.max_toxicity}"
                )

    return (not reasons), "; ".join(reasons), metrics


# ── The conductor ───────────────────────────────────────────────────────


def _default_make_trainer(data_path: Any, config: TrainerConfig) -> Any:
    from domain.training._internal.train_pipeline import SloughGPTTrainer

    return SloughGPTTrainer(data_path=data_path, config=config)


def _result_get(result: Any, key: str, default: Any = "") -> Any:
    """Read a field from a TrainResult (attribute- or dict-like)."""
    if isinstance(result, dict):
        return result.get(key, default)
    return getattr(result, key, None) or default


def run_curriculum(
    curriculum: Curriculum,
    *,
    config: TrainerConfig | None = None,
    make_trainer: Callable[[Any, TrainerConfig], Any] | None = None,
    on_progress: Callable[[dict[str, Any]], None] | None = None,
    cancel_event: threading.Event | None = None,
    pause_event: threading.Event | None = None,
) -> CurriculumReport:
    """Run every stage of ``curriculum`` over ONE trainer instance.

    The trainer is constructed for the first stage and *swapped* between
    stages (``swap_stage_data``) — model, optimizer, ``global_step`` and EWC
    consolidation history persist; the corpus and stage-local bookkeeping do
    not. EWC stages snapshot at their boundary under the stage's name (the
    named snapshot becomes the active penalty target for the next stage).

    Args:
        curriculum: a validated curriculum (see :func:`load_curriculum`).
        config: base trainer config; per-stage ``epochs`` (and ``use_ewc``
            when any stage requests it) are applied on top.
        make_trainer: injection point for tests — ``(data_path, config) ->
            trainer``; defaults to ``SloughGPTTrainer``.
        on_progress: receives train() progress dicts enriched with ``stage``,
            ``stage_index``, ``stages_total``, and a whole-curriculum
            ``progress_percent`` (0-100 across all stages).
        cancel_event: checked between stages and passed to ``train()``.
        pause_event: passed through to ``train()``.

    Returns:
        :class:`CurriculumReport` with one :class:`StageResult` per stage
        that completed.

    Raises:
        CurriculumError: empty curriculum.
        StageGateError: a stage failed its gate under ``on_gate_fail:
            "abort"`` (later stages never run).
    """
    if not curriculum.stages:
        raise _fail("nothing to run: curriculum has no stages")

    from domain.training._internal.train_pipeline import TrainerConfig as _TC

    base = config if config is not None else _TC()
    any_ewc = any(s.ewc for s in curriculum.stages)
    if any_ewc and not base.use_ewc:
        base = replace(base, use_ewc=True)

    make = make_trainer or _default_make_trainer
    total = len(curriculum.stages)
    completed_paths: list[str] = []
    results: list[StageResult] = []
    trainer: Any = None
    cancelled = False

    for idx, stage in enumerate(curriculum.stages):
        if cancel_event is not None and cancel_event.is_set():
            cancelled = True
            break

        mix = compute_stage_mix(stage, completed_paths)
        if trainer is None:
            trainer = make(mix, replace(base, epochs=stage.epochs))
            if any_ewc:
                # the runner owns snapshots at named stage boundaries —
                # train()'s anonymous post-run snapshot would double the
                # (expensive) Fisher estimation every stage.
                trainer.ewc_snapshot_after_train = False
        else:
            trainer.swap_stage_data(mix, epochs=stage.epochs)

        def _cb(info: dict[str, Any], _idx: int = idx, _stage: StageSpec = stage) -> None:
            if on_progress is None:
                return
            merged = dict(info)
            pct = float(merged.get("progress_percent", 0.0) or 0.0)
            merged["progress_percent"] = (_idx + pct / 100.0) / total * 100.0
            merged["stage"] = _stage.name
            merged["stage_index"] = _idx
            merged["stages_total"] = total
            on_progress(merged)

        result = trainer.train(
            on_progress=_cb,
            cancel_event=cancel_event,
            pause_event=pause_event,
        )

        if cancel_event is not None and cancel_event.is_set():
            cancelled = True
            break

        checkpoint = str(_result_get(result, "model_path", ""))
        eval_text = stage.eval_text or curriculum.eval_text or ""
        passed, reason, metrics = evaluate_stage_gate(
            trainer, stage, checkpoint=checkpoint, eval_text=eval_text
        )

        provisional = False
        if not passed:
            if stage.on_gate_fail == "abort":
                raise StageGateError(stage.name, reason, metrics)
            provisional = True
            logger.warning(
                "stage gate failed for %r — continuing (checkpoint provisional): %s",
                stage.name,
                reason,
            )

        results.append(
            StageResult(
                name=stage.name,
                passed=passed,
                provisional=provisional,
                metrics=metrics,
                checkpoint=checkpoint,
                gate_reason=reason,
                epochs=stage.epochs,
            )
        )

        if stage.ewc and any_ewc:
            if not trainer.save_ewc_snapshot(stage.name):
                logger.warning(
                    "EWC snapshot at stage boundary %r failed — the next stage "
                    "runs without a consolidation penalty",
                    stage.name,
                )

        completed_paths.extend(p for p, _ in stage.datasets)

    return CurriculumReport(
        stages=tuple(results),
        final_checkpoint=results[-1].checkpoint if results else "",
        total_stages=total,
        cancelled=cancelled,
    )
