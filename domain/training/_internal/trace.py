"""StepTrace — the per-step reduction set ("ship receipts, not cargo").

Design discussion 2026-11-02: a training step crosses the host/device
boundary with a *fixed, versioned* set of scalars instead of raw tensors.

What ships per step:
- live control signals (loss, lr, grad_norm) — decisions that cannot wait
  for a replay,
- bug tripwires (device residency, matmul path counters, steps/s) — the
  fields that would have exposed job_c87a2dd6 (0.4 steps/s, GPU idle,
  silent CPU fallback) on step 1 instead of hour 3,
- replay anchors (step, batch_fingerprint) — the receipt that lets any
  unshipped tensor be regenerated by re-running that step deterministically.

What never ships: full gradients, activations, raw batches. They are cargo,
regenerable by replay — shipping any of them means the reduction contract
was violated.

Schema ratchet: ``STEP_TRACE_FIELDS`` is the single declaration of the
trace's shape and must equal the ``StepTrace`` dataclass fields (enforced by
tests/test_step_trace.py). Fields may only be added with a version bump and
a reviewed edit — the page-baseline pattern.

v1 deliberately excludes queue_depth / update_norm / ES probe fields: they
require the async transfer pipeline and the evolution-strategies training
mode, neither of which exists yet. A field that cannot be populated
honestly waits for its version. No fake fields.
"""

from __future__ import annotations

import hashlib
from dataclasses import asdict, dataclass, fields

import numpy as np

STEP_TRACE_VERSION = 1

STEP_TRACE_FIELDS: tuple[str, ...] = (
    # --- identity / replay anchors ---
    "step",
    "batch_fingerprint",
    "tokens_this_step",
    # --- live control ---
    "loss",
    "raw_loss",
    "lr",
    "grad_norm",
    "skipped",
    # --- tripwires ---
    "steps_per_s",
    "device",
    "gpu_matmuls",
    "cpu_matmuls",
    "fallbacks",
    "h2d_bytes",
    "d2h_bytes",
)


@dataclass(frozen=True, slots=True)
class StepTrace:
    """One training step, reduced to its receipts. Immutable by design."""

    # identity / replay anchors
    step: int
    batch_fingerprint: str
    tokens_this_step: int
    # live control
    loss: float
    raw_loss: float
    lr: float
    grad_norm: float | None  # None = not a gradient-accumulation boundary
    skipped: bool
    # tripwires
    steps_per_s: float
    device: str
    gpu_matmuls: int  # eligible matmuls computed on an accelerator
    cpu_matmuls: int  # eligible matmuls computed on the CPU
    fallbacks: int  # accelerator attempts that raised and degraded to CPU
    h2d_bytes: int  # matmul-path host->device transfers (v1 scope)
    d2h_bytes: int  # matmul-path device->host transfers (v1 scope)

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


# Guard against the fields tuple and the dataclass drifting apart: one
# declaration, checked mechanically rather than by review attention.
assert STEP_TRACE_FIELDS == tuple(f.name for f in fields(StepTrace)), (
    "STEP_TRACE_FIELDS must list exactly the StepTrace dataclass fields"
)


def fingerprint_batch(x: np.ndarray) -> str:
    """Cheap content hash of a batch — the replay anchor.

    Deterministic across runs for identical bytes (blake2b, 8-byte digest →
    16 hex chars). Non-contiguous input is normalized first so layout never
    changes the receipt. Costs microseconds on real batch sizes (~16 KB),
    negligible against a training step.
    """
    arr = np.ascontiguousarray(x)
    return hashlib.blake2b(arr.tobytes(), digest_size=8).hexdigest()
