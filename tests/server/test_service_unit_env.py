"""The slough-api systemd unit must carry the project's environment contract.

Root cause (2026-10-09, card 12855e99): every other entry point into this
project runs with ``PYTHONNOUSERSITE=1`` — AGENTS.md mandates it for test runs
because a stray ``tests`` package in ``~/.local/lib/python3.12/site-packages``
shadows the repo's ``tests/`` and takes ``pytest`` itself down
(``ModuleNotFoundError: No module named 'tests.conftest'``).

The one exception was the long-lived ``slough-api.service``. Because its unit
lived only in ``~/.config/systemd/user/`` — untracked, generated by a script
that no longer existed in the repo (the unit header pointed at
``scripts/systemd/install.sh``, which was absent) — nothing could notice that
it had drifted. The consequence was silent: ``~/.local/lib/python3.12/site-packages``
(numpy 2.5.3, numba 0.67) shadowed the pinned conda env, so the live API
resolved a *different* module graph than the suite it was being judged against.

These tests close that by moving the source of truth into the repo. The unit is
now versioned at ``scripts/systemd/slough-api.service``, installed by
``scripts/systemd/install.sh``, and the live copy is treated as a deploy
artifact that must not drift from the canonical file.
"""

from __future__ import annotations

from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
CANONICAL = REPO / "scripts" / "systemd" / "slough-api.service"
LIVE = Path.home() / ".config" / "systemd" / "user" / "slough-api.service"


def _directives(text: str) -> dict[str, list[str]]:
    """Return ``{directive: [values]}``, ignoring comments and sections."""
    out: dict[str, list[str]] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("["):
            continue
        key, _, value = line.partition("=")
        out.setdefault(key.strip(), []).append(value.strip())
    return out


@pytest.fixture(scope="module")
def canonical() -> dict[str, list[str]]:
    assert CANONICAL.is_file(), (
        f"canonical unit missing: {CANONICAL} — it is the source of truth for "
        "the shared :8000 server and must stay in the repo"
    )
    return _directives(CANONICAL.read_text())


def test_unit_exists_in_repo(canonical: dict[str, list[str]]) -> None:
    """The unit is versioned, not hand-maintained in ~/.config."""
    assert canonical


def test_python_no_user_site_is_set(canonical: dict[str, list[str]]) -> None:
    """User-site must never shadow the pinned conda env in the long-lived server.

    This is the regression the card exists for: without it the live API drifts
    from every other entry point in the project.
    """
    # systemd treats quoting as literal, but strip it anyway so the assertion
    # survives someone "tidying" the value into "PYTHONNOUSERSITE=1".
    env = {value.strip('"') for value in canonical.get("Environment", [])}
    assert "PYTHONNOUSERSITE=1" in env, (
        "slough-api.service must set Environment=PYTHONNOUSERSITE=1; without it "
        "~/.local/lib/python3.12/site-packages shadows the conda env and the "
        "served module graph silently diverges from the one tests run against"
    )


def test_exec_start_uses_the_conda_interpreter(canonical: dict[str, list[str]]) -> None:
    """Project directive is conda, not ``.venv`` (which lacks ``setuptools``)."""
    exec_start = canonical.get("ExecStart", [""])[0]
    assert exec_start.startswith("/home/mana/miniconda3/envs/sloughgpt/bin/python"), (
        f"ExecStart must run the pinned conda interpreter, got: {exec_start!r}"
    )


def test_working_directory_is_the_checkout(canonical: dict[str, list[str]]) -> None:
    """``data/`` and ``models/`` are written under the checkout, so cwd matters."""
    wd = canonical.get("WorkingDirectory", [""])[0]
    assert wd and Path(wd).is_dir(), f"WorkingDirectory missing or absent: {wd!r}"


def test_unit_restarts_on_failure(canonical: dict[str, list[str]]) -> None:
    """The shared server must come back on its own — it outlives its launcher."""
    restart = canonical.get("Restart", [""])[0]
    assert restart in {"on-failure", "always"}, f"unexpected Restart={restart!r}"


def test_live_copy_matches_canonical() -> None:
    """The deployed unit must not drift from the versioned one.

    Skipped where no unit is installed (CI, other machines) — the in-repo file
    is still gated by the tests above.
    """
    if not LIVE.is_file():
        pytest.skip(f"no installed unit at {LIVE}")
    assert LIVE.read_bytes() == CANONICAL.read_bytes(), (
        f"{LIVE} has drifted from the canonical {CANONICAL}. "
        "Hand-edits to the live copy are how this unit lost PYTHONNOUSERSITE=1 "
        "in the first place — change scripts/systemd/slough-api.service and "
        "re-run scripts/systemd/install.sh instead."
    )
